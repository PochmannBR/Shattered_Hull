//Shattered Hull: sobrecarga do núcleo do Sintético, no lugar da trindade
public class SobrecargaNucleo extends ArmorAbility {

	{
		baseChargeUse = 35;
	}

	@Override
	protected void activate(ClassArmor armor, Hero hero, Integer target) {
		if (hero.buff(Sintetico.Sobrecarga.class) != null){
			GLog.w(Messages.get(this, "ativa"));
			return;
		}
		Buff.affect(hero, Sintetico.Sobrecarga.class, Sintetico.Sobrecarga.DURACAO);
		armor.charge -= chargeUse(hero);
		armor.updateQuickslot();
		Sample.INSTANCE.play(Assets.Sounds.CHARGEUP);
		if (hero.sprite != null) hero.sprite.operate(hero.pos);
		hero.spendAndNext(Actor.TICK);
	}

	@Override
	public int icon() {
		return HeroIcon.TRINITY;
	}

	@Override
	public Talent[] talents() {
		return new Talent[]{Talent.DISSIPACAO_CONTROLADA, Talent.VELOCIDADE_EXTREMA, Talent.PRIMEIRO_DISPARO, Talent.HEROIC_ENERGY};
	}
}
